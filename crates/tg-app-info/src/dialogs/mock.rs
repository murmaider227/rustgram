impl DialogsBackend for MockDialogsStore {
    fn current_time(&self) -> LocalDateTime {
        self.now
    }

    fn dialog_slice(&self, list: DialogListQuery, offset: usize, limit: usize) -> DialogSlice {
        let (ordered, pinned_count) = self.ordered_dialogs_for(list);
        let total = ordered.len();
        let start = offset.min(total);
        let end = start.saturating_add(limit).min(total);
        let entries = ordered[start..end].to_vec();
        DialogSlice {
            entries,
            total,
            pinned_count,
            has_more: end < total,
        }
    }

    fn dialog_by_peer(&self, peer_id: PeerId) -> Option<DialogItem> {
        self.dialogs.iter().find(|d| d.peer_id == peer_id).cloned()
    }

    fn chat_folders(&self) -> Vec<ChatFolder> {
        self.folders.clone()
    }

    fn reorder_folders(&mut self, order: &[FilterId]) {
        let mut reordered = Vec::with_capacity(self.folders.len());
        for &fid in order {
            if let Some(f) = self.folders.iter().find(|f| f.id == fid) {
                reordered.push(f.clone());
            }
        }
        for f in &self.folders {
            if !reordered.iter().any(|r| r.id == f.id) {
                reordered.push(f.clone());
            }
        }
        self.folders = reordered;
    }

    fn add_peer_to_folder(&mut self, peer_id: PeerId, filter_id: FilterId) {
        if filter_id == FilterId::ALL || filter_id == FOLDER_UNREAD {
            return;
        }
        let folder_info = self
            .folders
            .iter()
            .find(|f| f.id == filter_id)
            .map(|f| (f.title.clone(), f.color_index));
        if let Some(dialog) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id)
            && !dialog.folders.contains(&filter_id)
        {
            dialog.folders.push(filter_id);
            if let Some((title, color_index)) = folder_info {
                dialog.folder_tags.push(FolderTagBadge {
                    filter_id,
                    title,
                    color_index,
                });
            }
        }
        self.recompute_folder_unreads();
    }

    fn remove_peer_from_folder(&mut self, peer_id: PeerId, filter_id: FilterId) {
        if let Some(dialog) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            dialog.folders.retain(|&f| f != filter_id);
            dialog.folder_tags.retain(|t| t.filter_id != filter_id);
        }
        if let Some(pins) = self
            .pinned_orders
            .get_mut(&DialogListQuery::Filter(filter_id))
        {
            pins.retain(|&p| p != peer_id);
        }
        self.recompute_folder_unreads();
    }

    fn mark_folder_read(&mut self, filter_id: FilterId) {
        for d in &mut self.dialogs {
            if dialog_matches_list(d, DialogListQuery::Filter(filter_id)) {
                d.badges.unread = false;
                d.badges.unread_counter = 0;
                d.badges.mention = false;
                d.badges.reaction = false;
                d.badges.poll = false;
            }
        }
        self.recompute_folder_unreads();
    }

    fn archive_summary(&self) -> Option<ArchiveSummary> {
        let mut archived: Vec<&DialogItem> = self.dialogs.iter().filter(|d| d.archived).collect();
        if archived.is_empty() {
            return None;
        }
        archived.sort_by(|a, b| {
            b.display_time()
                .to_local_epoch_secs()
                .cmp(&a.display_time().to_local_epoch_secs())
        });
        let unread_count = archived.iter().filter(|d| d.badges.unread).count() as u32;
        let all_muted = archived
            .iter()
            .filter(|d| d.badges.unread)
            .all(|d| d.muted || d.badges.unread_muted);
        let preview_titles = archived.iter().take(5).map(|d| d.title.clone()).collect();
        Some(ArchiveSummary {
            chat_count: archived.len(),
            unread_count,
            all_muted,
            preview_titles,
            collapsed: self.archive_collapsed,
        })
    }

    fn archive_collapsed(&self) -> bool {
        self.archive_collapsed
    }

    fn set_archive_collapsed(&mut self, collapsed: bool) {
        self.archive_collapsed = collapsed;
    }

    fn toggle_archive(&mut self, peer_id: PeerId) -> bool {
        let mut new_archived = false;
        if let Some(d) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            if d.special == SpecialRowKind::SavedMessages {
                return false;
            }
            d.archived = !d.archived;
            new_archived = d.archived;
        }
        if new_archived {
            if let Some(pins) = self
                .pinned_orders
                .get_mut(&DialogListQuery::Filter(FilterId::ALL))
            {
                pins.retain(|&p| p != peer_id);
            }
        } else if let Some(pins) = self.pinned_orders.get_mut(&DialogListQuery::Archive) {
            pins.retain(|&p| p != peer_id);
        }
        self.sync_pinned_flags_for_all();
        self.recompute_folder_unreads();
        new_archived
    }

    fn mark_archive_read(&mut self) {
        for d in &mut self.dialogs {
            if d.archived {
                d.badges.unread = false;
                d.badges.unread_counter = 0;
                d.badges.mention = false;
                d.badges.reaction = false;
                d.badges.poll = false;
            }
        }
    }

    fn toggle_pin(&mut self, peer_id: PeerId, list: DialogListQuery) -> bool {
        let pins = self.pinned_orders.entry(list).or_default();
        let now_pinned = if let Some(pos) = pins.iter().position(|&p| p == peer_id) {
            pins.remove(pos);
            false
        } else {
            pins.insert(0, peer_id);
            true
        };
        if list == DialogListQuery::Filter(FilterId::ALL) {
            self.sync_pinned_flags_for_all();
        }
        now_pinned
    }

    fn reorder_pinned(
        &mut self,
        list: DialogListQuery,
        from_index: usize,
        to_index: usize,
    ) -> bool {
        let Some(pins) = self.pinned_orders.get_mut(&list) else {
            return false;
        };
        if from_index >= pins.len() || to_index >= pins.len() || from_index == to_index {
            return false;
        }
        let moved = pins.remove(from_index);
        pins.insert(to_index, moved);
        if list == DialogListQuery::Filter(FilterId::ALL) {
            self.sync_pinned_flags_for_all();
        }
        true
    }

    fn toggle_mute_dialog(&mut self, peer_id: PeerId) -> bool {
        let mut new_muted = false;
        if let Some(d) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            d.muted = !d.muted;
            d.badges.unread_muted = d.muted;
            new_muted = d.muted;
        }
        if let Some(tp) = self.top_peers.iter_mut().find(|p| p.peer_id == peer_id) {
            tp.muted = new_muted;
        }
        self.recompute_folder_unreads();
        new_muted
    }

    fn mark_dialog_read(&mut self, peer_id: PeerId) {
        if let Some(d) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            d.badges.unread = false;
            d.badges.unread_counter = 0;
            d.badges.mention = false;
            d.badges.reaction = false;
            d.badges.poll = false;
        }
        if let Some(tp) = self.top_peers.iter_mut().find(|p| p.peer_id == peer_id) {
            tp.unread_count = 0;
        }
        self.recompute_folder_unreads();
    }

    fn mark_dialog_unread(&mut self, peer_id: PeerId) {
        if let Some(d) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            d.badges.unread = true;
            if d.badges.unread_counter == 0 {
                d.badges.unread_counter = 1;
            }
        }
        self.recompute_folder_unreads();
    }

    fn clear_history(&mut self, peer_id: PeerId) {
        if let Some(d) = self.dialogs.iter_mut().find(|d| d.peer_id == peer_id) {
            d.last_message.clear();
            d.last_sender = None;
            d.last_message_id = MsgId(0);
            d.draft = None;
            d.send_state = DialogSendState::None;
            d.badges = DialogBadgesState::default();
        }
        self.messages.retain(|m| m.peer_id != peer_id);
        self.recompute_folder_unreads();
    }

    fn delete_dialog(&mut self, peer_id: PeerId) {
        self.dialogs.retain(|d| d.peer_id != peer_id);
        for pins in self.pinned_orders.values_mut() {
            pins.retain(|&p| p != peer_id);
        }
        self.messages.retain(|m| m.peer_id != peer_id);
        self.top_peers.retain(|p| p.peer_id != peer_id);
        self.recent_peers.retain(|&p| p != peer_id);
        self.recompute_folder_unreads();
    }

    fn search_dialogs(&self, request: &SearchRequest) -> SearchResults {
        let trimmed = request.query.trim();
        let lower = trimmed.to_lowercase();
        let mut results = SearchResults::default();

        // 1. Hashtags / cashtags when starting with `#` or `$`.
        if let Some(sigil) = trimmed.chars().next().filter(|&c| c == '#' || c == '$') {
            let prefix = lower[sigil.len_utf8()..].trim();
            if !prefix.contains(char::is_whitespace) {
                results.hashtags = self
                    .recent_hashtags
                    .iter()
                    .filter(|t| prefix.is_empty() || t.to_lowercase().starts_with(prefix))
                    .enumerate()
                    .map(|(i, tag)| HashtagSuggestion {
                        tag: tag.clone(),
                        sigil,
                        usage_count: (12 - (i % 9)) as u32,
                    })
                    .collect();
            }
        }

        if lower.is_empty() && request.selected_tag.is_none() {
            return results;
        }

        let clean_query = lower.strip_prefix('@').unwrap_or(&lower);
        let tab_allows_kind = |kind: DialogPeerKind| match request.tab {
            SearchTab::Chats => true,
            SearchTab::Channels => matches!(kind, DialogPeerKind::Channel),
            SearchTab::Apps => matches!(kind, DialogPeerKind::Bot),
            SearchTab::PublicPosts => matches!(kind, DialogPeerKind::Channel),
        };

        // 2. Local chats & contacts (skipped when searching inside a single peer or by tag only).
        if request.in_peer.is_none() && !lower.is_empty() && !trimmed.starts_with('#') {
            results.local_chats = self
                .dialogs
                .iter()
                .filter(|d| !request.in_archive || d.archived)
                .filter(|d| tab_allows_kind(d.kind))
                .filter(|d| request.chat_type_filter.matches(d.kind))
                .filter(|d| {
                    d.title.to_lowercase().contains(clean_query)
                        || d.username
                            .as_deref()
                            .is_some_and(|u| u.to_lowercase().contains(clean_query))
                })
                .take(20)
                .cloned()
                .collect();
        }

        // 3. Global peers (public channels, bots, groups matching query >= 2 chars).
        if request.in_peer.is_none()
            && !request.in_archive
            && clean_query.chars().count() >= 2
            && !trimmed.starts_with('#')
        {
            results.global_peers = self
                .global_peers
                .iter()
                .filter(|g| tab_allows_kind(g.kind))
                .filter(|g| request.chat_type_filter.matches(g.kind))
                .filter(|g| {
                    g.title.to_lowercase().contains(clean_query)
                        || g.username.to_lowercase().contains(clean_query)
                })
                .cloned()
                .collect();
        }

        // 4. Messages matching query and/or selected tag.
        let tag_filter = request
            .selected_tag
            .as_deref()
            .map(|t| format!("#{}", t.to_lowercase()));
        let matched_msgs: Vec<MessageSearchResult> = self
            .messages
            .iter()
            .filter(|m| request.in_peer.is_none_or(|p| m.peer_id == p))
            .filter(|m| !request.in_archive || m.archived)
            .filter(|m| tab_allows_kind(m.kind))
            .filter(|m| request.chat_type_filter.matches(m.kind))
            .filter(|m| {
                let text_l = m.text.to_lowercase();
                let query_ok = lower.is_empty() || text_l.contains(&lower);
                let tag_ok = tag_filter.as_deref().is_none_or(|tf| text_l.contains(tf));
                query_ok && tag_ok
            })
            .cloned()
            .collect();

        results.total_messages = matched_msgs.len();
        let limit = if request.messages_limit == 0 {
            50
        } else {
            request.messages_limit
        };
        let start = request.messages_offset.min(matched_msgs.len());
        let end = start.saturating_add(limit).min(matched_msgs.len());
        results.messages = matched_msgs[start..end].to_vec();
        results.has_more_messages = end < matched_msgs.len();
        results
    }

    fn top_peers(&self) -> Vec<TopPeerItem> {
        self.top_peers.clone()
    }

    fn remove_top_peer(&mut self, peer_id: PeerId) {
        self.top_peers.retain(|p| p.peer_id != peer_id);
    }

    fn recent_search_peers(&self) -> Vec<RecentPeerItem> {
        self.recent_peers
            .iter()
            .filter_map(|&pid| self.dialogs.iter().find(|d| d.peer_id == pid))
            .map(|d| RecentPeerItem {
                peer_id: d.peer_id,
                kind: d.kind,
                special: d.special,
                title: d.title.clone(),
                status: match d.kind {
                    DialogPeerKind::User if d.special == SpecialRowKind::SavedMessages => {
                        "cloud storage".to_owned()
                    }
                    DialogPeerKind::User if d.online => "online".to_owned(),
                    DialogPeerKind::User => "last seen recently".to_owned(),
                    DialogPeerKind::Bot => "bot".to_owned(),
                    DialogPeerKind::Group | DialogPeerKind::Forum => "20 members".to_owned(),
                    DialogPeerKind::Channel => "1,420 subscribers".to_owned(),
                },
                color_index: d.color_index,
                unread_count: d.badges.unread_counter.max(0) as u32,
                muted: d.muted,
                verified: d.verified,
            })
            .collect()
    }

    fn add_recent_search_peer(&mut self, peer_id: PeerId) {
        self.recent_peers.retain(|&p| p != peer_id);
        self.recent_peers.insert(0, peer_id);
        self.recent_peers.truncate(20);
    }

    fn remove_recent_search_peer(&mut self, peer_id: PeerId) {
        self.recent_peers.retain(|&p| p != peer_id);
    }

    fn clear_recent_search_peers(&mut self) {
        self.recent_peers.clear();
    }

    fn recent_hashtags(&self) -> Vec<String> {
        self.recent_hashtags.clone()
    }

    fn remove_recent_hashtag(&mut self, tag: &str) {
        let lower = tag.trim_start_matches(['#', '$']).to_lowercase();
        self.recent_hashtags.retain(|t| t.to_lowercase() != lower);
    }

    fn search_tags(&self) -> Vec<SearchTagChip> {
        self.search_tags.clone()
    }

    fn saved_messages_peer_id(&self) -> PeerId {
        PEER_SAVED_MESSAGES
    }
}

