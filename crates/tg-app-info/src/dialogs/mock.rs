fn mock_backend_stores() -> &'static Mutex<HashMap<usize, MockDialogsStore>> {
    static STORES: OnceLock<Mutex<HashMap<usize, MockDialogsStore>>> = OnceLock::new();
    STORES.get_or_init(|| Mutex::new(HashMap::new()))
}

fn with_mock_store<R>(backend: &MockBackend, f: impl FnOnce(&MockDialogsStore) -> R) -> R {
    let key = std::ptr::from_ref(backend) as usize;
    let mut guard = mock_backend_stores()
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let store = guard.entry(key).or_default();
    f(store)
}

fn with_mock_store_mut<R>(
    backend: &mut MockBackend,
    f: impl FnOnce(&mut MockDialogsStore) -> R,
) -> R {
    let key = std::ptr::from_ref(backend) as usize;
    let mut guard = mock_backend_stores()
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let store = guard.entry(key).or_default();
    f(store)
}

/// Drops any cached [`DialogsBackend`] state attached to a specific [`MockBackend`] address.
pub fn reset_mock_backend_dialogs_state(backend: &MockBackend) {
    let key = std::ptr::from_ref(backend) as usize;
    if let Ok(mut guard) = mock_backend_stores().lock() {
        guard.remove(&key);
    }
}

