fn generate_synthetic_dialog(idx: usize, now: LocalDateTime) -> DialogItem {
    let archived = idx < 24;
    let mod_kind = idx % 10;
    let (peer_id, kind, title, username, last_sender) = if mod_kind < 5 {
        let first = FIRST_NAMES[idx % FIRST_NAMES.len()];
        let last = LAST_NAMES[(idx * 7 + 3) % LAST_NAMES.len()];
        let suffix = if idx >= FIRST_NAMES.len() {
            format!(" #{}", idx / FIRST_NAMES.len() + 1)
        } else {
            String::new()
        };
        let title = format!("{first} {last}{suffix}");
        let uname = format!(
            "{}_{}_{}",
            first.to_lowercase(),
            last.to_lowercase(),
            idx + 10
        );
        (
            PeerId::from_user(10_000 + idx as u64),
            DialogPeerKind::User,
            title,
            Some(uname),
            None,
        )
    } else if mod_kind < 8 {
        let base = GROUP_TOPICS[idx % GROUP_TOPICS.len()];
        let title = if idx >= GROUP_TOPICS.len() {
            format!("{base} {}", idx / GROUP_TOPICS.len() + 1)
        } else {
            base.to_owned()
        };
        let sender = FIRST_NAMES[(idx * 3 + 1) % FIRST_NAMES.len()].to_owned();
        let kind = if idx % 15 == 6 {
            DialogPeerKind::Forum
        } else {
            DialogPeerKind::Group
        };
        (
            PeerId::from_chat(20_000 + idx as u64),
            kind,
            title,
            Some(format!("group_room_{}", idx + 1)),
            Some(sender),
        )
    } else if mod_kind == 8 {
        let base = CHANNEL_TOPICS[idx % CHANNEL_TOPICS.len()];
        let title = if idx >= CHANNEL_TOPICS.len() {
            format!("{base} {}", idx / CHANNEL_TOPICS.len() + 1)
        } else {
            base.to_owned()
        };
        (
            PeerId::from_channel(30_000 + idx as u64),
            DialogPeerKind::Channel,
            title,
            Some(format!("channel_feed_{}", idx + 1)),
            None,
        )
    } else {
        let title = format!("Helper Tool Bot {}", idx / 10 + 1);
        (
            PeerId::from_user(40_000 + idx as u64),
            DialogPeerKind::Bot,
            title,
            Some(format!("helper_tool_{}_bot", idx / 10 + 1)),
            None,
        )
    };

    let mut folders = Vec::new();
    match kind {
        DialogPeerKind::User => {
            folders.push(FOLDER_PERSONAL);
            if idx.is_multiple_of(3) {
                folders.push(FOLDER_WORK);
            }
        }
        DialogPeerKind::Group | DialogPeerKind::Forum => {
            folders.push(FOLDER_WORK);
        }
        DialogPeerKind::Channel => {
            folders.push(FOLDER_CHANNELS);
        }
        DialogPeerKind::Bot => {
            folders.push(FOLDER_BOTS);
        }
    }

    let muted = matches!(kind, DialogPeerKind::Channel) || idx.is_multiple_of(4) || archived;
    let unread_counter = match idx % 9 {
        0 => ((idx % 23) + 1) as i32,
        3 => ((idx % 7) + 1) as i32,
        6 => ((idx % 120) + 12) as i32,
        _ => 0,
    };
    let unread = unread_counter > 0;
    let badges = DialogBadgesState {
        unread_counter,
        unread,
        unread_muted: muted,
        mention: unread && idx.is_multiple_of(18),
        mention_muted: false,
        reaction: idx.is_multiple_of(29),
        reaction_muted: muted,
        poll: idx.is_multiple_of(37),
        poll_muted: muted,
    };

    // Spread timestamps across today, past 6 days, and older months.
    let offset_secs = match idx {
        0..=15 => (idx as i64 + 1) * 420,
        16..=60 => (idx as i64 - 14) * 9_600,
        _ => (idx as i64 - 50) * 86_400 + 3600,
    };
    let last_message_time = LocalDateTime::from_unix_utc(now.to_local_epoch_secs() - offset_secs);

    let send_state = if !unread && matches!(kind, DialogPeerKind::User) {
        match idx % 5 {
            0 => DialogSendState::Received,
            2 => DialogSendState::Sent,
            _ => DialogSendState::None,
        }
    } else {
        DialogSendState::None
    };

    let snippet = SAMPLE_SNIPPETS[idx % SAMPLE_SNIPPETS.len()].to_owned();
    let online = matches!(kind, DialogPeerKind::User) && idx % 6 == 1;
    let verified = matches!(kind, DialogPeerKind::Channel) && idx % 20 == 8;
    let premium = matches!(kind, DialogPeerKind::User) && idx % 11 == 2;
    let draft = if !unread && idx == 26 {
        Some(DialogDraft {
            text: "Following up on the icon metrics...".to_owned(),
            time: LocalDateTime::from_unix_utc(now.to_local_epoch_secs() - 600),
            is_reply: false,
            saving: false,
        })
    } else {
        None
    };

    let folder_tags = if idx < 35 {
        folders
            .iter()
            .take(1)
            .map(|&fid| {
                let (label, color) = if fid == FOLDER_WORK {
                    ("Work", 5)
                } else if fid == FOLDER_PERSONAL {
                    ("Personal", 3)
                } else if fid == FOLDER_CHANNELS {
                    ("Channels", 4)
                } else {
                    ("Bots", 1)
                };
                FolderTagBadge {
                    filter_id: fid,
                    title: label.to_owned(),
                    color_index: color,
                }
            })
            .collect()
    } else {
        Vec::new()
    };

    DialogItem {
        peer_id,
        kind,
        special: SpecialRowKind::None,
        title,
        username,
        color_index: tg_ui::userpic::decide_color_index(peer_id.bare()),
        verified,
        premium,
        online,
        active_call: false,
        muted,
        pinned: false,
        pinned_order: None,
        archived,
        folders,
        folder_tags,
        last_message_id: MsgId(10_000 + idx as i32),
        last_message: snippet,
        last_sender,
        last_message_time,
        send_state,
        draft,
        typing: None,
        badges,
        is_contact: false,
        media_preview: None,
        has_bot_app_button: matches!(kind, DialogPeerKind::Bot) && idx % 20 == 9,
    }
}

