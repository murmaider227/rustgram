#[test]
fn parse_real_lang_strings_zero_errors() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../resources/lang.strings");
    let content = std::fs::read_to_string(&path).expect("read resources/lang.strings");
    let pack = parse_lang_strings(&content).expect("parse resources/lang.strings with zero errors");

    assert_eq!(pack.entries.len(), KEYS_COUNT);
    assert_eq!(pack.tags.len(), TAGS_COUNT);
    assert!(
        pack.entries.len() > 8_000,
        "expected >8000 key slots, got {}",
        pack.entries.len()
    );
    assert!(
        pack.tags.len() >= 190,
        "expected >=190 tags, got {}",
        pack.tags.len()
    );

    // Count distinct plural bases and verify every plural group occupies 6 consecutive slots
    // and starts with the `count` tag.
    let mut plural_groups = 0usize;
    let mut i = 0;
    while i < pack.entries.len() {
        if let Some(ref base) = pack.entries[i].key_base {
            plural_groups += 1;
            for shift in 0..PLURAL_PART_COUNT {
                let entry = &pack.entries[i + shift];
                assert_eq!(entry.key_base.as_deref(), Some(base.as_str()));
                assert_eq!(entry.tags.first().map(String::as_str), Some("count"));
            }
            // English source always defines #one (1) and #other (5).
            assert!(
                !pack.entries[i + 1].value.is_empty(),
                "empty #one for {base}"
            );
            assert!(
                !pack.entries[i + 5].value.is_empty(),
                "empty #other for {base}"
            );
            i += PLURAL_PART_COUNT;
        } else {
            i += 1;
        }
    }
    assert!(
        plural_groups > 400,
        "expected >400 plural groups, got {plural_groups}"
    );

    // Verify lookup functions generated by build.rs
    let lang_name_idx = get_key_index("lng_language_name").expect("lng_language_name exists");
    assert_eq!(lang_name_idx, key_ids::lng_language_name);
    assert_eq!(get_original_value(lang_name_idx), "English");
    assert_eq!(key_name(lang_name_idx), Some("lng_language_name"));

    // Verify plural key indexing for all 6 suffixes
    let sec_base = key_ids::lng_seconds;
    assert!(is_plural_key(sec_base));
    assert_eq!(get_key_index("lng_seconds#zero"), Some(sec_base));
    assert_eq!(get_key_index("lng_seconds#one"), Some(sec_base + 1));
    assert_eq!(get_key_index("lng_seconds#two"), Some(sec_base + 2));
    assert_eq!(get_key_index("lng_seconds#few"), Some(sec_base + 3));
    assert_eq!(get_key_index("lng_seconds#many"), Some(sec_base + 4));
    assert_eq!(get_key_index("lng_seconds#other"), Some(sec_base + 5));
    assert!(is_tag_replaced(sec_base, tags::COUNT));
    assert!(!is_tag_replaced(sec_base, tags::USER));

    // Verify multi-tag plural key
    let unread_base = key_ids::lng_filter_unread_chats;
    assert!(is_plural_key(unread_base));
    assert!(is_tag_replaced(unread_base, tags::COUNT));
    assert!(is_tag_replaced(unread_base, tags::TEXT));
    assert_eq!(get_tag_index("count"), Some(tags::COUNT));
    assert_eq!(get_tag_index("type"), Some(tags::TYPE));

    // Verify newline escape preserved in lng_tray_icon_text
    let tray = get_original_value(key_ids::lng_tray_icon_text);
    assert!(
        tray.contains('\n'),
        "expected escaped newline in lng_tray_icon_text"
    );
}

#[test]
fn strings_parser_syntax_and_errors() {
    let sample = r#"
/* Multi-line
   comment with "quotes" inside */
"key_plain" = "Hello \"world\" \\ \n\t!"; // trailing comment
"key_tagged" = "Hi {user}, {count_items} items";
"key_plural#one" = "{count} item in {folder}";
"key_plural#other" = "{count} items";
"#;
    let pack = parse_lang_strings(sample).expect("parse sample");
    assert_eq!(pack.entries[0].key, "key_plain");
    assert_eq!(pack.entries[0].value, "Hello \"world\" \\ \n\t!");
    assert_eq!(pack.entries[1].tags, vec!["user", "count_items"]);
    // Plural group accumulates tags from both #one and #other
    assert_eq!(pack.entries[2].key_base.as_deref(), Some("key_plural"));
    assert_eq!(pack.entries[2].tags, vec!["count", "folder"]);
    assert_eq!(pack.entries[7].tags, vec!["count", "folder"]);

    // Relaxed mode accepts all 6 plural forms
    let relaxed = r#"
"items#zero" = "no items";
"items#one" = "{count} item";
"items#two" = "two items";
"items#few" = "{count} few";
"items#many" = "{count} many";
"items#other" = "{count} other";
"#;
    let pack6 = parse_lang_strings_with_options(relaxed, true).expect("parse 6 plurals");
    assert_eq!(pack6.entries.len(), 6);
    assert_eq!(pack6.entries[0].value, "no items");
    assert_eq!(pack6.entries[2].value, "two items");

    // Error cases
    assert!(parse_lang_strings(r#""a" = "1"; "a" = "2";"#).is_err());
    assert!(parse_lang_strings(r#""a" = "{count} bad";"#).is_err());
    assert!(parse_lang_strings(r#""a" = "{x} and {x}";"#).is_err());
    assert!(parse_lang_strings(r#""a" = "unterminated"#).is_err());
    assert!(parse_lang_strings(r#""a__b" = "double underscore";"#).is_err());
    assert!(parse_lang_strings(r#""a" = "{bad-tag}";"#).is_err());

    // Comment stripping preserves URLs inside string literals
    let stripped = strip_comments(br#""url" = "https://telegram.org/*keep*/"; // drop"#);
    let stripped_str = std::str::from_utf8(&stripped).unwrap();
    assert!(stripped_str.contains("https://telegram.org/*keep*/"));
    assert!(!stripped_str.contains("drop"));
}

#[test]
fn generated_tr_functions_and_runtime_fallback() {
    // Plain phrases
    assert_eq!(tr::lng_menu_settings(), "Settings");
    assert_eq!(tr::lng_language_name(), "English");

    // Tagged phrase
    assert_eq!(tr::lng_month_day("May", "15"), "May 15");
    assert_eq!(tr::lng_month_day_year("May", "15", "2026"), "May 15, 2026");

    // Plural phrases
    assert_eq!(tr::lng_seconds(1), "1 second");
    assert_eq!(tr::lng_seconds(0), "0 seconds");
    assert_eq!(tr::lng_seconds(42), "42 seconds");
    assert_eq!(tr::lng_seconds(PluralCount::short(12_345)), "12.3K seconds");
    assert_eq!(
        tr::lng_seconds(PluralCount::decimal(12_345)),
        "12,345 seconds"
    );

    // Plural phrase with additional tag
    assert_eq!(
        tr::lng_filter_unread_chats(1, "Work"),
        "Work (1 unread chat)"
    );
    assert_eq!(
        tr::lng_filter_unread_chats(5, "Work"),
        "Work (5 unread chats)"
    );

    // Switch global instance temporarily and verify tr:: reflects the cloud translation
    // while untranslated keys fall back to built-in English.
    with_current_mut(|inst| {
        inst.switch_to_id(&Language {
            id: "de".to_string(),
            plural_id: "de".to_string(),
            name: "German".to_string(),
            native_name: "Deutsch".to_string(),
            base_id: String::new(),
        });
        inst.apply_difference(
            Pack::Current,
            &LangPackDifference {
                lang_code: "de".to_string(),
                from_version: 0,
                version: 1,
                strings: vec![LangPackString::Normal {
                    key: "lng_menu_settings".to_string(),
                    value: "Einstellungen".to_string(),
                }],
            },
        )
        .expect("apply de diff");
    });

    assert_eq!(tr::lng_menu_settings(), "Einstellungen");
    assert_eq!(tr::lng_menu_contacts(), "Contacts"); // fallback to English

    // Restore global instance to English so other tests see clean defaults.
    with_current_mut(|inst| inst.switch_to_id(&Language::default_english()));
    assert_eq!(tr::lng_menu_settings(), "Settings");
}

