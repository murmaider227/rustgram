#[derive(Default)]
struct MockCloudClient {
    connected: bool,
    next_id: RequestId,
    calls: Vec<String>,
    reinit_count: usize,
}

impl MockCloudClient {
    fn new(connected: bool) -> Self {
        Self {
            connected,
            next_id: 1,
            calls: Vec::new(),
            reinit_count: 0,
        }
    }

    fn alloc_id(&mut self) -> RequestId {
        let id = self.next_id;
        self.next_id += 1;
        id
    }
}

impl LangCloudClient for MockCloudClient {
    fn is_connected(&self) -> bool {
        self.connected
    }

    fn request_languages(&mut self, lang_pack: &str) -> RequestId {
        self.calls.push(format!("getLanguages({lang_pack})"));
        self.alloc_id()
    }

    fn request_lang_pack(&mut self, lang_pack: &str, lang_code: &str) -> RequestId {
        self.calls
            .push(format!("getLangPack({lang_pack},{lang_code})"));
        self.alloc_id()
    }

    fn request_difference(
        &mut self,
        lang_pack: &str,
        lang_code: &str,
        from_version: i32,
    ) -> RequestId {
        self.calls.push(format!(
            "getDifference({lang_pack},{lang_code},{from_version})"
        ));
        self.alloc_id()
    }

    fn request_language(&mut self, lang_pack: &str, lang_code: &str) -> RequestId {
        self.calls
            .push(format!("getLanguage({lang_pack},{lang_code})"));
        self.alloc_id()
    }

    fn request_strings(
        &mut self,
        lang_pack: &str,
        lang_code: &str,
        keys: Vec<String>,
    ) -> RequestId {
        self.calls.push(format!(
            "getStrings({lang_pack},{lang_code},{})",
            keys.join(",")
        ));
        self.alloc_id()
    }

    fn cancel_request(&mut self, request_id: RequestId) {
        self.calls.push(format!("cancel({request_id})"));
    }

    fn reinit_connection(&mut self) {
        self.reinit_count += 1;
    }
}

#[test]
fn cloud_manager_suggested_language_and_pack_sync() {
    let mut inst = Instance::new();
    let mut client = MockCloudClient::new(true);
    let mut mgr = CloudManager::new(CloudManagerConfig {
        can_apply_without_restart: true,
        offer_legacy_lang_pack_switch: true,
    });

    // Suggested English clears suggestion
    let actions = mgr.set_suggested_language(&inst, "en", &mut client);
    assert_eq!(mgr.suggested_language(), "");
    assert_eq!(
        actions,
        vec![CloudAction::FirstLanguageSuggestion(String::new())]
    );

    // Fresh manager suggesting "uk" triggers getLanguages -> OfferSwitchLanguage
    let mut mgr2 = CloudManager::new(CloudManagerConfig {
        can_apply_without_restart: true,
        offer_legacy_lang_pack_switch: true,
    });
    let a1 = mgr2.set_suggested_language(&inst, "uk", &mut client);
    assert_eq!(mgr2.suggested_language(), "uk");
    assert_eq!(
        a1,
        vec![CloudAction::FirstLanguageSuggestion("uk".to_string())]
    );
    assert!(client.calls.last().unwrap().starts_with("getLanguages"));

    let a2 = mgr2.on_languages_received(&[LangPackLanguageInfo {
        official: true,
        lang_code: "uk".to_string(),
        plural_code: "uk".to_string(),
        name: "Ukrainian".to_string(),
        native_name: "Українська".to_string(),
        strings_count: 100,
        translated_count: 99,
        ..LangPackLanguageInfo::default()
    }]);
    assert!(a2.contains(&CloudAction::LanguageListChanged));
    assert!(
        a2.iter()
            .any(|a| matches!(a, CloudAction::OfferSwitchLanguage(l) if l.id == "uk"))
    );

    // Switch to language with base pack -> requests both Current and Base packs
    client.calls.clear();
    let lang = Language {
        id: "pt-br".to_string(),
        plural_id: "pt".to_string(),
        base_id: "pt".to_string(),
        name: "Portuguese (Brazil)".to_string(),
        native_name: "Português (Brasil)".to_string(),
    };
    let actions = mgr2.switch_to_language(&mut inst, &lang, &mut client);
    assert_eq!(actions, vec![CloudAction::PushRecentLanguage(lang)]);
    assert_eq!(client.reinit_count, 1);
    assert!(
        client
            .calls
            .contains(&"getLangPack(tdesktop,pt-br)".to_string())
    );
    assert!(
        client
            .calls
            .contains(&"getLangPack(tdesktop,pt)".to_string())
    );

    // Apply initial diff, then set_current_versions triggers getDifference (version > 0)
    let diff_actions = mgr2
        .apply_lang_pack_difference(
            &mut inst,
            &LangPackDifference {
                lang_code: "pt-br".to_string(),
                from_version: 0,
                version: 5,
                strings: vec![LangPackString::Normal {
                    key: "lng_menu_settings".to_string(),
                    value: "Configurações".to_string(),
                }],
            },
            &mut client,
        )
        .expect("apply diff");
    assert_eq!(diff_actions, vec![CloudAction::WriteLangPack]);

    client.calls.clear();
    mgr2.set_current_versions(&inst, 8, 3, &mut client);
    assert_eq!(client.calls, vec!["getDifference(tdesktop,pt-br,5)"]);
}

#[test]
fn cloud_manager_offline_resend_and_warnings() {
    let mut inst = Instance::new();
    let mut client = MockCloudClient::new(false);
    let mut mgr = CloudManager::new(CloudManagerConfig {
        can_apply_without_restart: false,
        offer_legacy_lang_pack_switch: false,
    });

    // Offline requests queue and fire on reconnect
    mgr.request_language_list(&mut client);
    mgr.switch_with_warning(&inst, "ru", &mut client);
    mgr.get_value_for_lang("lng_language_name", "ru", &mut client);
    assert!(client.calls.is_empty());

    client.connected = true;
    mgr.resend_requests(&inst, &mut client);
    assert!(client.calls.contains(&"getLanguages(tdesktop)".to_string()));
    assert!(
        client
            .calls
            .contains(&"getLanguage(tdesktop,ru)".to_string())
    );
    assert!(
        client
            .calls
            .contains(&"getStrings(tdesktop,ru,lng_language_name)".to_string())
    );

    // Warning response with 0 strings -> LanguageNotReady
    let empty_info = LangPackLanguageInfo {
        lang_code: "xx".to_string(),
        strings_count: 0,
        ..LangPackLanguageInfo::default()
    };
    assert_eq!(
        mgr.on_language_received(&mut inst, &empty_info, &mut client),
        vec![CloudAction::LanguageNotReady(empty_info)]
    );

    // Warning response with >0 strings -> ConfirmSwitchWithWarning
    let ready_info = LangPackLanguageInfo {
        lang_code: "ru".to_string(),
        plural_code: "ru".to_string(),
        name: "Russian".to_string(),
        native_name: "Русский".to_string(),
        strings_count: 1000,
        translated_count: 950,
        ..LangPackLanguageInfo::default()
    };
    assert_eq!(ready_info.translated_percent(), 95);
    assert_eq!(
        mgr.on_language_received(&mut inst, &ready_info, &mut client),
        vec![CloudAction::ConfirmSwitchWithWarning(ready_info)]
    );
}

