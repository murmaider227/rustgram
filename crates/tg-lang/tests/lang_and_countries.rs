#[test]
fn shortened_counts_and_number_formatting() {
    let s1 = format_count_to_short(9_999, false);
    assert!(!s1.shortened);
    assert_eq!(s1.string, "9999");

    let s2 = format_count_to_short(10_000, false);
    assert!(s2.shortened);
    assert_eq!(s2.string, "10K");

    let s3 = format_count_to_short(12_345, false);
    assert!(s3.shortened);
    assert_eq!(s3.string, "12.3K");

    let s4 = format_count_to_short(1_500_000, false);
    assert_eq!(s4.string, "1.5M");

    let s5 = format_count_to_short(1_500_000, true);
    assert_eq!(s5.string, "1500K");

    let s6 = format_count_to_short(2_400_000_000, false);
    assert_eq!(s6.string, "2.4B");

    assert_eq!(format_count_decimal(0), "0");
    assert_eq!(format_count_decimal(1234), "1,234");
    assert_eq!(format_count_decimal(-1_234_567), "-1,234,567");
    assert_eq!(format_double(1.500_000), "1.5");
    assert_eq!(format_double(42.0), "42");
    assert_eq!(format_exact_count_decimal(1234.5), "1,234.5");
    assert_eq!(format_exact_count_decimal(1000.0), "1,000");

    let stars = CreditsAmount::new(12, 500_000_000, CreditsType::Stars);
    assert_eq!(format_credits_amount_decimal(stars), "12.5");
    assert_eq!(
        format_credits_amount_rounded(CreditsAmount::new(1, 236_000_000, CreditsType::Ton)),
        "1.24"
    );
    assert_eq!(
        format_credits_amount_to_short(CreditsAmount::from_whole(25_400, CreditsType::Stars))
            .string,
        "25.4K"
    );

    // Plural with CountShort
    let pr = plural_with_rule(
        PluralRule::for_language("ru"),
        true,
        12_345.0,
        CountFormat::CountShort,
    );
    assert_eq!(pr.replacement, "12.3K");
    assert_eq!(pr.form, PluralForm::Many);
}

#[test]
fn tag_replacement_high_tag_index_and_entities_and_numbers() {
    // High tag ID (>= 96) produces a 2-byte UTF-8 encoded 3rd character (5 bytes total).
    let high_tag: u16 = 150;
    let template = format!("Prefix {} suffix", prepare_command_string(high_tag));
    assert_eq!(
        replace_tag_str(template.clone(), high_tag, "VALUE"),
        "Prefix VALUE suffix"
    );

    // StringWithNumbers records exact UTF-8 byte offset & length.
    let swn = replace_tag_numbers(
        StringWithNumbers {
            text: format!("Привет {} мир", prepare_command_string(high_tag)),
            offset: None,
            length: 0,
        },
        high_tag,
        "42",
    );
    assert_eq!(swn.text, "Привет 42 мир");
    assert_eq!(swn.offset, Some("Привет ".len()));
    assert_eq!(swn.length, 2);

    // TextWithEntities adjusts offsets across multi-byte tag replacement.
    let marker = prepare_command_string(high_tag);
    let orig_text = format!("Hello {marker} world");
    let world_start = orig_text.find("world").unwrap();
    let orig = TextWithEntities {
        text: orig_text,
        entities: vec![TextEntity {
            entity_type: 1,
            offset: world_start,
            length: 5,
            data: String::new(),
        }],
    };
    let repl = TextWithEntities {
        text: "Alice".to_string(),
        entities: vec![TextEntity {
            entity_type: 2,
            offset: 0,
            length: 5,
            data: "bold".to_string(),
        }],
    };
    let merged = replace_tag_entities(orig, high_tag, &repl);
    assert_eq!(merged.text, "Hello Alice world");
    assert_eq!(merged.entities.len(), 2);
    assert_eq!(
        &merged.text
            [merged.entities[0].offset..merged.entities[0].offset + merged.entities[0].length],
        "Alice"
    );
    assert_eq!(
        &merged.text
            [merged.entities[1].offset..merged.entities[1].offset + merged.entities[1].length],
        "world"
    );
}

