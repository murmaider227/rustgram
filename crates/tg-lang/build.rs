//! Build-time code generator from `resources/lang.strings`.
//!
//! Port of `Telegram/codegen/codegen/lang/generator.cpp`.

use std::collections::HashMap;
use std::env;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::path::PathBuf;

#[path = "src/strings_parser.rs"]
mod strings_parser;

use strings_parser::{PLURAL_PART_COUNT, PLURAL_PARTS, parse_lang_strings};

fn is_rust_keyword(ident: &str) -> bool {
    matches!(
        ident,
        "as" | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "gen"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "Self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "macro"
            | "override"
            | "priv"
            | "try"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
    )
}

fn sanitize_ident(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if is_rust_keyword(&cleaned) {
        format!("r#{cleaned}")
    } else {
        cleaned
    }
}

fn sanitize_const_ident(name: &str) -> String {
    let upper: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if is_rust_keyword(&upper) {
        format!("r#{upper}")
    } else {
        upper
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let lang_path = manifest_dir.join("../../resources/lang.strings");
    println!("cargo:rerun-if-changed={}", lang_path.display());
    println!("cargo:rerun-if-changed=src/strings_parser.rs");

    let content = fs::read_to_string(&lang_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", lang_path.display()));
    let pack = parse_lang_strings(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", lang_path.display()));

    let keys_count = pack.entries.len();
    let tags_count = pack.tags.len();
    assert!(
        keys_count < usize::from(u16::MAX),
        "key table exceeds u16::MAX ({keys_count})"
    );
    assert!(
        tags_count < usize::from(u16::MAX),
        "tag table exceeds u16::MAX ({tags_count})"
    );

    let mut tag_map: HashMap<&str, u16> = HashMap::with_capacity(tags_count);
    for (i, tag) in pack.tags.iter().enumerate() {
        tag_map.insert(tag.as_str(), i as u16);
    }

    let mut out = String::with_capacity(2 * 1024 * 1024);
    out.push_str("// @generated by crates/tg-lang/build.rs from resources/lang.strings.\n");
    out.push_str("// Do not edit manually.\n\n");

    let _ = writeln!(
        out,
        "/// Total number of key slots (including 6 slots per plural phrase)."
    );
    let _ = writeln!(out, "pub const KEYS_COUNT: usize = {keys_count};");
    let _ = writeln!(out, "/// Total number of unique placeholder tags.");
    let _ = writeln!(out, "pub const TAGS_COUNT: usize = {tags_count};");
    let _ = writeln!(
        out,
        "/// Tag ID for the built-in `count` plural placeholder."
    );
    let count_tag_id = *tag_map.get("count").expect("'count' tag must exist");
    let _ = writeln!(out, "pub const COUNT_TAG_ID: u16 = {count_tag_id};\n");

    // Concatenated default UTF-8 data and byte offsets.
    let mut default_data = String::new();
    let mut offsets: Vec<u32> = Vec::with_capacity(keys_count + 1);
    for entry in &pack.entries {
        offsets.push(default_data.len() as u32);
        default_data.push_str(&entry.value);
    }
    offsets.push(default_data.len() as u32);

    out.push_str("static DEFAULT_DATA: &str = ");
    let _ = writeln!(out, "{default_data:?};");

    out.push_str("static DEFAULT_OFFSETS: &[u32] = &[\n");
    for chunk in offsets.chunks(16) {
        out.push_str("    ");
        for off in chunk {
            let _ = write!(out, "{off}, ");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");

    // Packed tag lists per key for O(1) is_tag_replaced.
    let mut packed_tags: Vec<u16> = Vec::new();
    let mut key_tag_ranges: Vec<(u32, u8)> = Vec::with_capacity(keys_count);
    for entry in &pack.entries {
        let start = packed_tags.len() as u32;
        for tag in &entry.tags {
            packed_tags.push(tag_map[tag.as_str()]);
        }
        key_tag_ranges.push((start, entry.tags.len() as u8));
    }

    out.push_str("static PACKED_KEY_TAGS: &[u16] = &[\n");
    for chunk in packed_tags.chunks(16) {
        out.push_str("    ");
        for id in chunk {
            let _ = write!(out, "{id}, ");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");

    out.push_str("static KEY_TAG_RANGES: &[(u32, u8)] = &[\n");
    for chunk in key_tag_ranges.chunks(8) {
        out.push_str("    ");
        for (start, len) in chunk {
            let _ = write!(out, "({start}, {len}), ");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");

    // Sorted (tag_name, id) table.
    let mut sorted_tags: Vec<(&str, u16)> = pack
        .tags
        .iter()
        .enumerate()
        .map(|(i, t)| (t.as_str(), i as u16))
        .collect();
    sorted_tags.sort_unstable_by_key(|&(name, _)| name);

    out.push_str("static SORTED_TAGS: &[(&str, u16)] = &[\n");
    for (name, id) in &sorted_tags {
        let _ = writeln!(out, "    ({name:?}, {id}),");
    }
    out.push_str("];\n\n");

    // Sorted (key_name, key_index) table including base#zero..#other for plurals.
    let mut key_lookup: Vec<(String, u16)> = Vec::with_capacity(keys_count);
    let mut key_names_by_idx: Vec<String> = Vec::with_capacity(keys_count);
    let mut plural_bases: Vec<u16> = Vec::new();
    let mut i = 0;
    while i < keys_count {
        let entry = &pack.entries[i];
        if let Some(ref base) = entry.key_base {
            plural_bases.push(i as u16);
            for (shift, part) in PLURAL_PARTS.iter().enumerate() {
                let full_name = format!("{base}#{part}");
                key_lookup.push((full_name.clone(), (i + shift) as u16));
                key_names_by_idx.push(full_name);
            }
            i += PLURAL_PART_COUNT;
        } else {
            key_lookup.push((entry.key.clone(), i as u16));
            key_names_by_idx.push(entry.key.clone());
            i += 1;
        }
    }
    key_lookup.sort_unstable_by(|a, b| a.0.cmp(&b.0));

    out.push_str("static SORTED_KEYS: &[(&str, u16)] = &[\n");
    for (name, id) in &key_lookup {
        let _ = writeln!(out, "    ({name:?}, {id}),");
    }
    out.push_str("];\n\n");

    out.push_str("static KEY_NAMES: &[&str] = &[\n");
    for name in &key_names_by_idx {
        let _ = writeln!(out, "    {name:?},");
    }
    out.push_str("];\n\n");

    out.push_str("static PLURAL_KEY_BASES: &[u16] = &[\n");
    for chunk in plural_bases.chunks(16) {
        out.push_str("    ");
        for id in chunk {
            let _ = write!(out, "{id}, ");
        }
        out.push('\n');
    }
    out.push_str("];\n\n");

    // Tag constants module.
    out.push_str("/// Generated placeholder tag IDs (analogous to `lt_*` in Telegram Desktop).\n");
    out.push_str("pub mod tags {\n");
    for (idx, tag) in pack.tags.iter().enumerate() {
        let cname = sanitize_const_ident(tag);
        let _ = writeln!(out, "    /// Tag ID for `{{{tag}}}`.");
        let _ = writeln!(out, "    pub const {cname}: u16 = {idx};");
    }
    out.push_str("}\n\n");

    // Core lookup functions matching Lang::GetTagIndex, GetKeyIndex, IsTagReplaced, GetOriginalValue.
    out.push_str(
        r#"/// Look up a placeholder tag's numeric index by name (`Lang::GetTagIndex`).
#[inline]
pub fn get_tag_index(tag: &str) -> Option<u16> {
    SORTED_TAGS
        .binary_search_by_key(&tag, |&(name, _)| name)
        .ok()
        .map(|pos| SORTED_TAGS[pos].1)
}

/// Look up a phrase key's numeric slot index by name (`Lang::GetKeyIndex`).
///
/// Plural variants use the `<base>#<part>` syntax (e.g. `"lng_seconds#one"`).
#[inline]
pub fn get_key_index(key: &str) -> Option<u16> {
    SORTED_KEYS
        .binary_search_by_key(&key, |&(name, _)| name)
        .ok()
        .map(|pos| SORTED_KEYS[pos].1)
}

/// Return whether `tag` is an expected placeholder in `key` (`Lang::IsTagReplaced`).
#[inline]
pub fn is_tag_replaced(key: u16, tag: u16) -> bool {
    let Some(&(start, len)) = KEY_TAG_RANGES.get(usize::from(key)) else {
        return false;
    };
    let start = start as usize;
    let end = start + usize::from(len);
    PACKED_KEY_TAGS[start..end].contains(&tag)
}

/// Return the built-in English value for `key` (`Lang::GetOriginalValue`).
#[inline]
pub fn get_original_value(key: u16) -> &'static str {
    let idx = usize::from(key);
    let start = DEFAULT_OFFSETS[idx] as usize;
    let end = DEFAULT_OFFSETS[idx + 1] as usize;
    &DEFAULT_DATA[start..end]
}

/// Return the canonical key name for `key`, if in range.
#[inline]
pub fn key_name(key: u16) -> Option<&'static str> {
    KEY_NAMES.get(usize::from(key)).copied()
}

/// Return whether `key_base` is the base slot of a 6-variant plural phrase.
#[inline]
pub fn is_plural_key(key_base: u16) -> bool {
    PLURAL_KEY_BASES.binary_search(&key_base).is_ok()
}

/// Return the slice of expected tag IDs for `key`.
#[inline]
pub fn key_tags(key: u16) -> &'static [u16] {
    let Some(&(start, len)) = KEY_TAG_RANGES.get(usize::from(key)) else {
        return &[];
    };
    let start = start as usize;
    let end = start + usize::from(len);
    &PACKED_KEY_TAGS[start..end]
}

"#,
    );

    // Key constants module (`key_ids`) for direct slot indexing / Instance lookups.
    out.push_str("/// Numeric key slot constants for every phrase in `resources/lang.strings`.\n");
    out.push_str("#[allow(non_upper_case_globals, dead_code)]\n");
    out.push_str("pub mod key_ids {\n");
    let mut i = 0;
    while i < keys_count {
        let entry = &pack.entries[i];
        let is_plural = entry.key_base.is_some();
        let name = entry.key_base.as_deref().unwrap_or(&entry.key);
        let ident = sanitize_ident(name);
        let _ = writeln!(out, "    /// Key slot index for `{name}`.");
        let _ = writeln!(out, "    pub const {ident}: u16 = {i};");
        i += if is_plural { PLURAL_PART_COUNT } else { 1 };
    }
    out.push_str("}\n\n");

    // Generated `tr` module with one typed function per phrase!
    out.push_str("/// Typed phrase lookup functions generated from `resources/lang.strings`.\n");
    out.push_str("///\n");
    out.push_str(
        "/// Each function resolves through the active global [`crate::Instance`], falling back\n",
    );
    out.push_str("/// to the built-in English text when no translation is loaded.\n");
    out.push_str("#[allow(non_snake_case, clippy::too_many_arguments, dead_code)]\n");
    out.push_str("pub mod tr {\n");
    out.push_str("    use crate::tag::PluralCount;\n\n");

    let mut i = 0;
    while i < keys_count {
        let entry = &pack.entries[i];
        let is_plural = entry.key_base.is_some();
        let name = entry.key_base.as_deref().unwrap_or(&entry.key);
        let fn_name = sanitize_ident(name);

        if !is_plural && entry.tags.is_empty() {
            let _ = writeln!(out, "    /// Phrase `{name}`.");
            let _ = writeln!(out, "    #[inline]");
            let _ = writeln!(out, "    pub fn {fn_name}() -> String {{");
            let _ = writeln!(out, "        crate::instance::lookup_plain({i})");
            let _ = writeln!(out, "    }}");
        } else if !is_plural {
            let _ = writeln!(out, "    /// Phrase `{name}`.");
            let _ = writeln!(out, "    #[inline]");
            let _ = write!(out, "    pub fn {fn_name}(");
            for (ti, tag) in entry.tags.iter().enumerate() {
                if ti > 0 {
                    out.push_str(", ");
                }
                let p = sanitize_ident(tag);
                let _ = write!(out, "{p}: &str");
            }
            out.push_str(") -> String {\n");
            let _ = write!(out, "        crate::instance::lookup_tagged({i}, &[");
            for (ti, tag) in entry.tags.iter().enumerate() {
                if ti > 0 {
                    out.push_str(", ");
                }
                let tid = tag_map[tag.as_str()];
                let p = sanitize_ident(tag);
                let _ = write!(out, "({tid}, {p})");
            }
            out.push_str("])\n    }\n");
        } else {
            // Plural phrase: entry.tags[0] is always "count".
            let _ = writeln!(out, "    /// Plural phrase `{name}`.");
            let _ = writeln!(out, "    #[inline]");
            let _ = write!(out, "    pub fn {fn_name}(count: impl Into<PluralCount>");
            for tag in entry.tags.iter().skip(1) {
                let p = sanitize_ident(tag);
                let _ = write!(out, ", {p}: &str");
            }
            out.push_str(") -> String {\n");
            let _ = write!(
                out,
                "        crate::instance::lookup_plural({i}, count.into(), &["
            );
            for (ti, tag) in entry.tags.iter().skip(1).enumerate() {
                if ti > 0 {
                    out.push_str(", ");
                }
                let tid = tag_map[tag.as_str()];
                let p = sanitize_ident(tag);
                let _ = write!(out, "({tid}, {p})");
            }
            out.push_str("])\n    }\n");
        }

        i += if is_plural { PLURAL_PART_COUNT } else { 1 };
    }
    out.push_str("}\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let dest = out_dir.join("lang_auto.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("failed to write {}: {e}", dest.display()));
}
